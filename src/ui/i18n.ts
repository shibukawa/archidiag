export const COPY: Record<Locale, typeof en> = { en, ja }
export type Copy = typeof en

export function roleLabel(copy: Copy, element: Element) {
  if (element.kind === 'entity') return element.classification ? copy.classifications[element.classification] : copy.kinds.entity
  if (element.kind === 'topic' || element.kind === 'folder') return copy.kinds[element.kind]
  if (element.kind !== 'container') return copy.kinds[element.kind]
  if (effectiveCategory(element) === 'dataStore') return copy.dataStoreKinds[element.dataStoreKind ?? 'other']
  return copy.kinds.container
}

export function viewTitle(copy: Copy, project: Project, view: DiagramView) {
  const scope = view.scopeId ? project.elements[view.scopeId]?.name ?? '?' : (Object.values(project.elements).find((element) => element.kind === 'softwareSystem' && !element.parentId)?.name ?? project.name)
  // DFD title: "DFD: <use case> / <system>" (requirement: use-case-dfd); an item store's list is titled Items.
  if (isDfdView(view.kind)) return `${copy.viewKinds[view.kind]}: ${view.useCase || view.name || '?'} / ${scope}`
  const scopeElement = view.scopeId ? project.elements[view.scopeId] : undefined
  const base = `${view.kind === 'erd_component' && isItemStore(scopeElement) ? copy.itemsView : copy.viewKinds[view.kind]}: ${scope}`
  return view.name && !view.isDefault ? `${base} (${view.name})` : base
}

/** Tab label of a DFD in the navigator and the explorer. */
export function dfdLabel(copy: Copy, view: DiagramView) {
  return view.useCase || view.name || copy.viewKinds[view.kind]
}

export function renderLabels(copy: Copy, project: Project, view: DiagramView, subtitle?: string): RenderLabels {
  const scope = view.scopeId ? project.elements[view.scopeId] : undefined
  const outer = view.kind === 'c4_component' && scope?.parentId ? project.elements[scope.parentId] : undefined
  return {
    kind: (element) => roleLabel(copy, element),
    storage: (element) => copy.storages[element.storageKind ?? 'table'],
    boundary: view.scopeId ? project.elements[view.scopeId]?.name ?? '' : '',
    boundaryKind: view.scopeId && project.elements[view.scopeId] ? `[${roleLabel(copy, project.elements[view.scopeId])}]` : undefined,
    outerBoundary: outer?.name,
    outerBoundaryKind: outer ? `[${roleLabel(copy, outer)}]` : undefined,
    title: viewTitle(copy, project, view),
    subtitle,
    legend: {
      heading: copy.legend,
      relationship: copy.legendLabels.relationship,
      projectedRelationship: copy.legendLabels.projected,
      boundaryRelationship: copy.legendLabels.boundaryRelationship,
      boundary: copy.legendLabels.boundary,
      outerBoundary: copy.legendLabels.outerBoundary,
      group: copy.legendLabels.group,
      externalContext: copy.legendLabels.externalContext,
      kinds: copy.tokens,
      applicationKinds: copy.applicationKinds,
      erdKinds: copy.erdKinds,
      entityView: copy.legendView,
    },
    moreFields: copy.moreFields,
    fieldCount: copy.fieldCount,
    dfd: { roles: copy.roles, intermediate: copy.intermediateKinds, consistency: copy.consistencies, free: copy.dfdFree, flow: copy.dfdFlowLegend, refTo: copy.refTo, missingRef: copy.missingRef, group: copy.processGroup, foldedFlow: copy.foldedFlow, handledBy: copy.handledBy, returnLane: copy.returnLane, start: copy.startLegend },
    placeholder: copy.placeholderContainer,
  }
}
